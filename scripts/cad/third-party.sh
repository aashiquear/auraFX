#!/usr/bin/env bash
# Regenerate docs/reference/third-party.md: the licence of every crate aurafx-cad builds on
# (from cargo metadata), grouped by licence. Run it after a pull or a dependency change.
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"; cd "$root"
cargo metadata --format-version 1 --manifest-path crates/aurafx-cad/Cargo.toml > "${TMPDIR:-/tmp}/afx-cad-meta.json"
python3 - "${TMPDIR:-/tmp}/afx-cad-meta.json" > docs/reference/third-party.md <<'PY'
import json, sys, collections
m = json.load(open(sys.argv[1]))
pk = {p["id"]: p for p in m["packages"]}
nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
root = [i for i, p in pk.items() if p["name"] == "aurafx-cad"][0]
seen, stack = set(), [root]
while stack:
    i = stack.pop()
    if i in seen: continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
            stack.append(d["pkg"])
def where(p):
    s = p["source"] or ""
    path = p["manifest_path"]
    if "/vendor/solidcraft/" in path: return "vendor/solidcraft"
    if "/vendor/solidcore/" in path: return "vendor/solidcore"
    if path.find("/crates/aurafx-") >= 0: return "auraFX"
    return "crates.io" if s.startswith("registry") else (s or "path")
rows = collections.defaultdict(list)
for i in sorted(seen, key=lambda i: pk[i]["name"]):
    p = pk[i]; w = where(p)
    if w == "auraFX": continue
    rows[(w, p.get("license") or "(no SPDX field)")].append(f'{p["name"]} {p["version"]}')
print("# Third-party code in the CAD environment\n")
print("The B-rep kernel and the CAD file formats are carried in this repository under `vendor/`")
print("(`vendor/README.md` says how, and how upstream work is taken). This table is generated by")
print("`scripts/cad/third-party.sh` from `cargo metadata` of `aurafx-cad`: every crate its build")
print("uses that is not auraFX's own, grouped by where it comes from and its SPDX licence.\n")
print("auraFX credits SolidCraft (https://github.com/tangency-labs/solidcraft, MIT OR Apache-2.0)")
print("and solidcore (https://github.com/tangency-labs/solidcore, Apache-2.0) as libraries; the")
print("parametric part model, sketch solver and expression evaluator were ported from the")
print("author's own EZ-YX-craft project (MIT OR Apache-2.0).\n")
for (w, lic), names in sorted(rows.items(), key=lambda kv: (kv[0][0] != "vendor/solidcraft", kv[0][0] != "vendor/solidcore", kv[0][0], kv[0][1])):
    print(f"## {w}: {lic}\n")
    print(", ".join(names) + "\n")
PY
echo wrote docs/reference/third-party.md
