/// The element with atomic number `z` (unknown elements give entry 0).
pub fn element(z: i64) -> &'static Element {
    ELEMENTS.get(z.max(0) as usize).unwrap_or(&ELEMENTS[0])
}

/// The atomic number of a symbol such as "C", "cl" or "CL" (0 if unknown).
pub fn atomic_number(symbol: &str) -> usize {
    let s = symbol.trim();
    ELEMENTS.iter().position(|e| e.symbol.eq_ignore_ascii_case(s)).filter(|&z| z > 0).unwrap_or(0)
}
